def insert_after_stage(s, after_id, block):
    key = 'id: "%s", juan' % after_id
    i = s.index(key)
    # 从该处向后找块结束 "    },\n"
    j = s.index("    },\n", i)
    return s[:j + len("    },\n")] + block + s[j + len("    },\n"):]

